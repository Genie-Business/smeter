const INT8 = 20;
const NUMERIC = 1700;

/** `?` placeholders to `$1, $2...` (ignores ? inside quoted strings). */
export function toPg(sql) {
  let n = 0;
  let out = '';
  let quote = null;
  for (const ch of sql) {
    if (quote) {
      if (ch === quote) quote = null;
    } else if (ch === "'" || ch === '"') {
      quote = ch;
    } else if (ch === '?') {
      out += `$${++n}`;
      continue;
    }
    out += ch;
  }
  return out;
}

async function pgDriver(url, schema) {
  const { default: pg } = await import('pg');
  pg.types.setTypeParser(INT8, Number);
  pg.types.setTypeParser(NUMERIC, Number);
  const pool = new pg.Pool({
    // Neon hands out `sslmode=require`; pg already treats it as verify-full
    // (and warns), so say so explicitly to keep full certificate checks.
    connectionString: url.replace(/([?&]sslmode=)(require|prefer|verify-ca)\b/, '$1verify-full'),
    max: Number(process.env.PG_POOL_MAX) || (config.onVercel ? 3 : 10),
    idleTimeoutMillis: 10_000,
    connectionTimeoutMillis: 10_000,
  });
  pool.on('error', (err) => console.error('[db] idle client error', err.message));
  // Tests run in their own schema. (Not for Neon's pooled URL, which doesn't
  // keep session settings between transactions.)
  if (schema) {
    if (!/^[a-z_][a-z0-9_]*$/.test(schema)) throw new Error('Invalid schema name');
    pool.on('connect', (c) => c.query(`SET search_path TO ${schema}`).catch(() => {}));
  }
  const wrap = (c) => ({
    query: async (text, params) => {
      const r = await c.query(text, params);
      return { rows: r.rows, rowCount: r.rowCount ?? 0 };
    },
  });
  return {
    kind: 'postgres',
    ...wrap(pool),
    exec: (sql) => pool.query(sql),
    async transaction(fn) {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const out = await fn(wrap(client));
        await client.query('COMMIT');
        return out;
      } catch (err) {
        await client.query('ROLLBACK').catch(() => {});
        throw err;
      } finally {
        client.release();
      }
    },
    close: () => pool.end(),
  };
}

async function pgliteDriver(dir) {
  const { PGlite } = await import('@electric-sql/pglite');
  if (dir !== 'memory') mkdirSync(dir, { recursive: true });
  const parsers = { [INT8]: Number, [NUMERIC]: Number };
  const pglite = await PGlite.create(dir === 'memory' ? undefined : dir, { parsers });
  const wrap = (c) => ({
    query: async (text, params) => {
      const r = await c.query(text, params);
      return { rows: r.rows, rowCount: r.affectedRows ?? r.rows.length };
    },
  });
  return {
    kind: 'pglite',
    ...wrap(pglite),
    exec: (sql) => pglite.exec(sql),
    // PGlite runs one transaction at a time; other queries wait for it.
    transaction: (fn) => pglite.transaction((t) => fn(wrap(t))),
    close: () => pglite.close(),
  };
}

async function open({ url, dir, schema }) {
  const driver = url ? await pgDriver(url, schema) : await pgliteDriver(dir);
  // Concurrent cold starts serialise on an advisory lock while creating tables.
  await driver.transaction(async (t) => {
    await t.query('SELECT pg_advisory_xact_lock(727274)');
    const statements = SCHEMA.replace(/--[^\n]*/g, '').split(';').map((s) => s.trim()).filter(Boolean);
    for (const stmt of statements) {
      await t.query(stmt);
    }
  });
  return driver;
}

let opening;
const store = new AsyncLocalStorage();

/** Open (once) and migrate. Call before serving traffic. */
export function initDb(target = { url: config.databaseUrl, dir: config.pgliteDir }) {
  opening ??= open(target).catch((err) => {
    opening = undefined;
    throw err;
  });
  return opening;
}

/** Tests: swap in a fresh database (e.g. `{ dir: 'memory' }`). */
export async function resetDb(target) {
  const previous = opening;
  opening = undefined;
  if (previous) await (await previous.catch(() => null))?.close?.();
  return initDb(target);
}

export async function closeDb() {
  const previous = opening;
  opening = undefined;
  if (previous) await (await previous.catch(() => null))?.close?.();
}

async function query(sql, params) {
  const conn = store.getStore() ?? (await initDb());
  return conn.query(toPg(sql), params.map((p) => (p === undefined ? null : p)));
}

const handle = {
  get: async (sql, ...params) => (await query(sql, params)).rows[0],
  all: async (sql, ...params) => (await query(sql, params)).rows,
  run: async (sql, ...params) => {
    const r = await query(sql, params);
    return { changes: r.rowCount, rows: r.rows };
  },
};

export function db() {
  return handle;
}

/** Run fn in a transaction; nested calls join the outer one. */
export async function tx(fn) {
  if (store.getStore()) return fn();
  const driver = await initDb();
  return driver.transaction((conn) => store.run(conn, fn));
}

export function now() {
  return new Date().toISOString();
}
