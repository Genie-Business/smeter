// Postgres persistence. Production/staging use Neon (DATABASE_URL, via `pg`);
// local development and tests use PGlite, an in-process Postgres, so nothing
// needs installing. Money is stored as integer kobo; timestamps as ISO-8601 text.
//
// Queries are written with `?` placeholders and go through db():
//   await db().get(sql, ...params)   first row or undefined
//   await db().all(sql, ...params)   all rows
//   await db().run(sql, ...params)   { changes, rows } (add RETURNING to get ids)
// Inside tx(fn) every db() call made by fn (or anything it calls) runs on the
// transaction's connection.
